    <p class="font-semibold text-cyan-200">Persiapan perangkat dan Jangan Ganggu</p>
    <details class="mt-2 text-xs leading-6">
        <summary class="cursor-pointer">Cara menyiapkan HP sebelum masuk ujian</summary>
        <p class="mt-2">Android: buka Setelan → Suara/Notifikasi → Jangan Ganggu (Do Not Disturb), atau gunakan tombol Jangan Ganggu di panel cepat. Nama menu dapat berbeda tiap HP.</p>
        <p class="mt-2">iPhone: buka Pengaturan → Fokus → Jangan Ganggu. Atur panggilan dan notifikasi yang diizinkan sesuai arahan pengawas.</p>
        <p class="mt-2">Tutup bubble/chat mengambang dan aplikasi lain, gunakan satu layar, pastikan baterai serta koneksi siap, lalu kembali ke halaman ini. Pengaturan dilakukan sebelum menekan tombol masuk ujian.</p>
        <p class="mt-2">Situs tidak dapat menyalakan atau memeriksa Jangan Ganggu pada sistem HP. Aktifkan manual jika tersedia. Jika layar penuh tidak didukung, pemantauan perpindahan tab/aplikasi tetap berjalan.</p>
